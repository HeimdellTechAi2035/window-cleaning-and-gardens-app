import { describe, it, expect, vi, beforeEach } from "vitest";

vi.mock("next/cache", () => ({ revalidatePath: vi.fn() }));
vi.mock("@/lib/auth", () => ({ auth: vi.fn() }));
vi.mock("@/lib/route-optimizer", () => ({ geocodeAddress: vi.fn() }));
vi.mock("@/lib/rounds", () => ({
  upsertAreaRound: vi.fn(async () => ({ id: "round-1", name: "Preston" })),
  assignPropertyToRound: vi.fn(),
  findConflictingRound: vi.fn(async () => null),
  deleteRoundIfEmptyAndAutoGenerated: vi.fn(),
}));
vi.mock("@/lib/prisma", () => ({
  prisma: {
    customer: { update: vi.fn() },
    property: { findFirst: vi.fn(), findFirstOrThrow: vi.fn(), update: vi.fn() },
  },
}));

import { prisma } from "@/lib/prisma";
import { auth } from "@/lib/auth";
import { geocodeAddress } from "@/lib/route-optimizer";
import { updatePropertyPinAction, resetPropertyPinToAutomaticAction, updateCustomerAction } from "@/app/actions/customers";

// eslint-disable-next-line @typescript-eslint/no-explicit-any -- Prisma's generated types are impractical to hand-mock; these tests cover action logic, not Prisma's type surface.
const db = prisma as any;
const mockAuth = auth as unknown as ReturnType<typeof vi.fn>;
const mockGeocode = geocodeAddress as unknown as ReturnType<typeof vi.fn>;

const SESSION = { user: { id: "user-1", organizationId: "org-1" } };

beforeEach(() => {
  vi.clearAllMocks();
});

describe("updatePropertyPinAction", () => {
  it("rejects when there is no session", async () => {
    mockAuth.mockResolvedValue(null);
    const result = await updatePropertyPinAction("prop-1", 53.76, -2.7);
    expect(result).toEqual({ error: "Not authenticated" });
    expect(db.property.findFirst).not.toHaveBeenCalled();
  });

  it("rejects out-of-range or non-finite coordinates without touching the database", async () => {
    mockAuth.mockResolvedValue(SESSION);

    expect(await updatePropertyPinAction("prop-1", 200, -2.7)).toEqual({ error: "Invalid coordinates" });
    expect(await updatePropertyPinAction("prop-1", 53.76, 400)).toEqual({ error: "Invalid coordinates" });
    expect(await updatePropertyPinAction("prop-1", NaN, -2.7)).toEqual({ error: "Invalid coordinates" });
    expect(db.property.findFirst).not.toHaveBeenCalled();
  });

  it("scopes the property lookup to the caller's own organisation", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.property.findFirst.mockResolvedValue(null);

    const result = await updatePropertyPinAction("someone-elses-property", 53.76, -2.7);

    expect(db.property.findFirst).toHaveBeenCalledWith({
      where: { id: "someone-elses-property", customer: { organizationId: "org-1" } },
      select: { id: true },
    });
    expect(result).toEqual({ error: "Property not found" });
    expect(db.property.update).not.toHaveBeenCalled();
  });

  it("saves the dragged position and locks the property against future auto-geocoding", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.property.findFirst.mockResolvedValue({ id: "prop-1" });

    const result = await updatePropertyPinAction("prop-1", 53.76, -2.7);

    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1" },
      data: { latitude: 53.76, longitude: -2.7, coordinatesLocked: true },
    });
    expect(result).toEqual({ ok: true });
  });
});

describe("resetPropertyPinToAutomaticAction", () => {
  it("rejects when there is no session", async () => {
    mockAuth.mockResolvedValue(null);
    const result = await resetPropertyPinToAutomaticAction("prop-1");
    expect(result).toEqual({ error: "Not authenticated" });
  });

  it("scopes the lookup to the caller's own organisation", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.property.findFirst.mockResolvedValue(null);

    const result = await resetPropertyPinToAutomaticAction("someone-elses-property");

    expect(result).toEqual({ error: "Property not found" });
    expect(mockGeocode).not.toHaveBeenCalled();
  });

  it("re-geocodes and unlocks the property", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.property.findFirst.mockResolvedValue({
      id: "prop-1",
      addressLine1: "59 Kingsfold Drive",
      city: "Preston",
      postcode: "PR1 1AA",
    });
    mockGeocode.mockResolvedValue({ latitude: 53.76, longitude: -2.7 });

    const result = await resetPropertyPinToAutomaticAction("prop-1");

    expect(mockGeocode).toHaveBeenCalledWith({
      addressLine1: "59 Kingsfold Drive",
      city: "Preston",
      postcode: "PR1 1AA",
    });
    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1" },
      data: { coordinatesLocked: false, latitude: 53.76, longitude: -2.7 },
    });
    expect(result).toEqual({ ok: true });
  });

  it("still unlocks the property even when re-geocoding fails, without touching its coordinates", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.property.findFirst.mockResolvedValue({
      id: "prop-1",
      addressLine1: "1 Nowhere Road",
      city: "Nowhereton",
      postcode: "",
    });
    mockGeocode.mockResolvedValue(null);

    const result = await resetPropertyPinToAutomaticAction("prop-1");

    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1" },
      data: { coordinatesLocked: false },
    });
    expect(result).toEqual({ ok: true });
  });
});

describe("updateCustomerAction — respects a locked pin on address edits", () => {
  function formDataFor(overrides: Record<string, string> = {}) {
    const fd = new FormData();
    fd.set("customerId", "cust-1");
    fd.set("firstName", "Jane");
    fd.set("lastName", "Doe");
    fd.set("preferredPaymentMethod", "CASH");
    fd.set("propertyId", "prop-1");
    fd.set("addressLine1", "60 Kingsfold Drive");
    fd.set("city", "Preston");
    fd.set("postcode", "PR1 1AA");
    for (const [k, v] of Object.entries(overrides)) fd.set(k, v);
    return fd;
  }

  it("does not re-geocode or touch coordinates when the property's pin is locked", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.customer.update.mockResolvedValue({});
    db.property.findFirstOrThrow.mockResolvedValue({ roundLocked: false, coordinatesLocked: true });
    db.property.update.mockResolvedValue({});

    const result = await updateCustomerAction(formDataFor());

    expect(mockGeocode).not.toHaveBeenCalled();
    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1", customerId: "cust-1" },
      data: { addressLine1: "60 Kingsfold Drive", city: "Preston", postcode: "PR1 1AA" },
    });
    expect(result).toEqual({ ok: true });
  });

  it("still re-geocodes normally when the property's pin is not locked", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.customer.update.mockResolvedValue({});
    db.property.findFirstOrThrow.mockResolvedValue({ roundLocked: false, coordinatesLocked: false });
    db.property.update.mockResolvedValue({});
    mockGeocode.mockResolvedValue({ latitude: 53.76, longitude: -2.7 });

    const result = await updateCustomerAction(formDataFor());

    expect(mockGeocode).toHaveBeenCalledTimes(1);
    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1", customerId: "cust-1" },
      data: {
        addressLine1: "60 Kingsfold Drive",
        city: "Preston",
        postcode: "PR1 1AA",
        latitude: 53.76,
        longitude: -2.7,
      },
    });
    expect(result).toEqual({ ok: true });
  });

  it("rejects a partial postcode (outward code only) with a clean, readable error", async () => {
    mockAuth.mockResolvedValue(SESSION);

    const result = await updateCustomerAction(formDataFor({ postcode: "PR1" }));

    expect(result).toEqual({
      error: "Enter a full UK postcode, e.g. PR1 1AA — not just the first part",
    });
    expect(db.property.update).not.toHaveBeenCalled();
    expect(mockGeocode).not.toHaveBeenCalled();
  });

  it("normalizes a lowercase, unspaced postcode before saving it", async () => {
    mockAuth.mockResolvedValue(SESSION);
    db.customer.update.mockResolvedValue({});
    db.property.findFirstOrThrow.mockResolvedValue({ roundLocked: false, coordinatesLocked: false });
    db.property.update.mockResolvedValue({});
    mockGeocode.mockResolvedValue({ latitude: 53.76, longitude: -2.7 });

    await updateCustomerAction(formDataFor({ postcode: "pr11aa" }));

    expect(db.property.update).toHaveBeenCalledWith({
      where: { id: "prop-1", customerId: "cust-1" },
      data: expect.objectContaining({ postcode: "PR1 1AA" }),
    });
  });
});
